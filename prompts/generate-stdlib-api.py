#!/usr/bin/env python3
"""Write prompts/neura/references/stdlib-api.md from the standard library sources.

The Neura agent skill (prompts/neura/) carries a signature index of every public
standard library module so an agent can look up exact names and types without
reading the library. This script regenerates it from stdlib/std/:

    python3 prompts/generate-stdlib-api.py

For each module outside an `internal` directory it lists, in source order, the
exported declarations (their signature up to the body), the class, interface,
and singleton headers that give those members their context, and the members of
interfaces, which are declared without `export`. Declarations tagged `#Hidden`
are left out with their members, and the `#Deprecated` and `#Since` tags of a
declaration are kept before its signature. Pass `--check` to fail when the
committed file is out of date instead of writing it.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STDLIB = ROOT / "stdlib" / "std"
OUTPUT = ROOT / "prompts" / "neura" / "references" / "stdlib-api.md"

# File-name components whose module names are not plain PascalCase.
SPECIAL = {
    "b-float16": "BFloat16",
    "u-int8": "UInt8",
    "u-int16": "UInt16",
    "u-int32": "UInt32",
    "u-int64": "UInt64",
    "int-range": "IntRange",
    "dynamic-foreign": "DynamicForeign",
}

HEADER = """# Standard library API index

Generated by `prompts/generate-stdlib-api.py` from `stdlib/std/`; do not edit by hand. Each section lists one
`Std` module: its exported declarations up to their bodies, in source order, with the class, interface, and
singleton headers that give members their context (two spaces of indentation mean "member of the type above").
Interface members appear without `export` because interfaces declare them that way.

Search this file instead of reading it whole, for example `grep -n "export let create" stdlib-api.md` or
`grep -n -A40 '### .Std.Collections.HashMap.' stdlib-api.md`. The import of a module is `import:` plus the
heading, such as `let maps = import:Std.Collections.HashMap;`. The full source of each module is in the installed
library below `share/neura/stdlib/std/`.
"""

DECLARATION = re.compile(r"^(export\s|or\s+func\b|or\s+as\b)")
CONTEXT = re.compile(r"^(static\s+)?let\s+\w+\s*=\s*(class|interface|singleton)\b")
INTERFACE = re.compile(r"=\s*interface\b")
INTERFACE_MEMBER = re.compile(r"^(static\s+)?(let|const)\s+\w+\s*=\s*func\b")
ENUM_OPEN = re.compile(r"=\s*enum(<[^>]*>)?\s*\($")
SIGNATURE_END = re.compile(r"(=>|\{|;|\($|\)\s*;?$)")
# Tags shown before a signature.
LISTED_TAGS = {"Deprecated", "Since"}


def split_tags(text):
    """Split the tags written at the start of a line (docs/lang/Tags.md) from
    the rest of it: (["Deprecated(as_of: \"0.2.0\")", "Since(\"0.1.0\")"], rest).
    A group `#[A, B]` gives one entry per tag."""
    tags = []
    rest = text.lstrip()
    while rest.startswith("#"):
        depth, quote, index = 0, False, 1
        while index < len(rest):
            char = rest[index]
            if quote:
                if char == "\\":
                    index += 1
                elif char == '"':
                    quote = False
            elif char == '"':
                quote = True
            elif char in "([":
                depth += 1
            elif char in ")]":
                depth -= 1
            elif depth == 0 and (char.isspace() or char == "#"):
                break
            index += 1
        body = rest[1:index]
        if body.startswith("[") and body.endswith("]"):
            depth, quote, start = 0, False, 1
            for position in range(1, len(body) - 1):
                char = body[position]
                if quote:
                    quote = char != '"' or body[position - 1] == "\\"
                elif char == '"':
                    quote = True
                elif char in "([":
                    depth += 1
                elif char in ")]":
                    depth -= 1
                elif char == "," and depth == 0:
                    tags.append(body[start:position].strip())
                    start = position + 1
            if body[start:-1].strip():
                tags.append(body[start:-1].strip())
        elif body:
            tags.append(body)
        rest = rest[index:].lstrip()
    return tags, rest


def tag_name(tag):
    """The name of a tag as split_tags returns it."""
    return re.match(r"[A-Za-z_]\w*", tag)[0] if re.match(r"[A-Za-z_]\w*", tag) else ""


def module_name(path: Path) -> str:
    parts = path.relative_to(STDLIB).with_suffix("").parts
    return "Std." + ".".join(SPECIAL.get(part, "".join(word[:1].upper() + word[1:] for word in part.split("-")))
                             for part in parts)


def strip_comment(text: str) -> str:
    return re.sub(r"\s*//.*$", "", text)


def signatures(path: Path) -> list[str]:
    lines = path.read_text(encoding="utf-8").split("\n")
    result = []
    interface_indent = None
    hidden_indent = None
    pending = []
    index = 0
    while index < len(lines):
        line = lines[index]
        indent = len(line) - len(line.lstrip())
        tags, text = split_tags(line)
        text = text.strip()
        if tags and not text:
            # A line of tags only; they belong to the declaration below.
            pending += tags
            index += 1
            continue
        if text and not text.startswith("//"):
            tags, pending = pending + tags, []
        if hidden_indent is not None and text and indent <= hidden_indent:
            hidden_indent = None
        if interface_indent is not None and text and indent <= interface_indent:
            interface_indent = None
        in_interface = interface_indent is not None and indent > interface_indent
        if hidden_indent is not None:
            index += 1
            continue
        if any(tag_name(tag) == "Hidden" for tag in tags):
            hidden_indent = indent
            index += 1
            continue
        if DECLARATION.match(text) or CONTEXT.match(text) or (in_interface and INTERFACE_MEMBER.match(text)):
            if INTERFACE.search(text):
                interface_indent = indent
            signature = strip_comment(text)
            if ENUM_OPEN.search(signature):
                end = index
                while signature.count("(") > signature.count(")") and end + 1 < len(lines):
                    end += 1
                    piece = strip_comment(lines[end].strip())
                    if piece:
                        signature += ("" if signature.endswith("(") else " ") + piece
                signature = signature.replace("( ", "(").replace(" )", ")")
                index = end
            else:
                end = index
                while not SIGNATURE_END.search(signature) and end + 1 < len(lines) and end - index < 6:
                    end += 1
                    signature += " " + strip_comment(lines[end].strip())
            signature = re.sub(r"\s*=>.*$", "", signature)
            signature = re.sub(r"\s*\{\s*$", "", signature)
            if "enum" not in signature and signature.count("{") > signature.count("}"):
                signature = re.sub(r"\s*\{[^}]*$", "", signature)
            signature = signature.rstrip(";").rstrip()
            listed = [tag for tag in tags if tag_name(tag) in LISTED_TAGS]
            if listed:
                signature = (f"#{listed[0]} " if len(listed) == 1 else f"#[{', '.join(listed)}] ") + signature
            depth = max(indent // 4 - 1, 0)
            result.append("  " * depth + signature)
        index += 1
    return result


def render() -> str:
    files = sorted((path for path in STDLIB.rglob("*.nra") if "internal" not in path.relative_to(STDLIB).parts),
                   key=module_name)
    sections = [HEADER]
    for path in files:
        body = "\n".join(signatures(path))
        sections.append(f"## `{module_name(path)}`\n\n```text\n{body}\n```\n")
    return "\n".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed index is out of date")
    arguments = parser.parse_args()
    text = render()
    if arguments.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run prompts/generate-stdlib-api.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
