#!/usr/bin/env python3
"""Run boundary arithmetic at tiers 0, 1, and 2 and compare every byte.

For each integer width and signedness, and for float32 and float64, the
script writes a program whose operations each get a block of their own (a
function per operation, called on values chosen at run time, so nothing is
folded at compile time). Every case is one argument list `<op> <i> <j>`:
the operation applied to values i and j of the type's boundary list, with
its result printed exactly (integers in decimal, floats as their bits), or
its trap. All cases of a program run in one process with `run --each`, so
the image's lifted blocks are shared by its cases as they are by the tests
of `neura test`.

Each program runs at --tier=0, at --tier=1 and --tier=2, and at each of
those with NEURA_TIER_CHECK=1, all but the first with NEURA_TIER_EAGER=1 so
that every block is lifted, and every region formed, when it first runs
(under the check, every tier-1 step is also evaluated by reference and every
region run again block by block, aborting on a difference). Status,
standard output, and standard error must be identical, and --tier-stats
must show that tier 1 ran lifted blocks and tier 2 ran regions.

    scripts/tier-boundary.py --neura build/neura --out build/tier-boundary
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

INTEGERS = [("int8", 8, True), ("int16", 16, True), ("int32", 32, True), ("int64", 64, True),
            ("uint8", 8, False), ("uint16", 16, False), ("uint32", 32, False), ("uint64", 64, False)]


def integer_values(width, signed):
    if signed:
        low, high = -(1 << (width - 1)), (1 << (width - 1)) - 1
        return [low, low + 1, -100, -2, -1, 0, 1, 2, 37, high - 1, high]
    high = (1 << width) - 1
    return [0, 1, 2, 3, 37, high // 2, high // 2 + 1, high - 1, high]


BINARY = ["+", "-", "*", "/", "%", "&", "|", "^", "<<", ">>", "==", "!=", "<", "<=", ">", ">="]


def integer_program(name, width, signed):
    values = integer_values(width, signed)
    lines = [
        "// Generated by scripts/tier-boundary.py: boundary arithmetic of " + name + ".",
        "let console = import:Std.Io.Console;",
        "let int64s = import:Std.Core.Int64;",
        "let program = import:Std.Program;",
        "let result = import:Std.Core.Result;",
        "",
        "let Boundary = module:program.Entry (",
    ]
    for k, op in enumerate(BINARY):
        result_type = "bool" if op in ("==", "!=", "<", "<=", ">", ">=") else name
        lines.append(f"    let op{k} = func(a: {name}, b: {name}) -> {result_type} {{")
        lines.append(f"        return a {op} b;")
        lines.append("    };")
    unary = [("neg", "-a", name), ("not", "~a", name)]
    conversions = [t for t, _, _ in INTEGERS] + ["float32", "float64"]
    for k, (label, expression, result_type) in enumerate(unary):
        lines.append(f"    let u{k} = func(a: {name}) -> {result_type} {{")
        lines.append(f"        return {expression};")
        lines.append("    };")
    for k, target in enumerate(conversions):
        lines.append(f"    let c{k} = func(a: {name}) -> {target} {{")
        lines.append(f"        return a as {target};")
        lines.append("    };")
    lines.append("    let text = func(b: bool) -> string {")
    lines.append('        if (b) { return "true"; }')
    lines.append('        return "false";')
    lines.append("    };")
    lines.append("    export let.override main = func(args: string[]) -> program.ExitCode {")
    lines.append("        let values: " + name + "[] = [" + ", ".join(str(v) for v in values) + "];")
    lines.append("        let op = result.value_or<int64>(int64s.parse(args[0]), 0);")
    lines.append("        let i = result.value_or<int64>(int64s.parse(args[1]), 0) as int;")
    lines.append("        let j = result.value_or<int64>(int64s.parse(args[2]), 0) as int;")
    lines.append("        let a = values[i];")
    lines.append("        let b = values[j];")
    for k, op in enumerate(BINARY):
        if op in ("==", "!=", "<", "<=", ">", ">="):
            lines.append(f"        if (op == {k}) {{ console.print_line(text(op{k}(a, b))); }}")
        else:
            lines.append(f"        if (op == {k}) {{ console.print_line(op{k}(a, b).to_string()); }}")
    base = len(BINARY)
    for k in range(len(unary)):
        lines.append(f"        if (op == {base + k}) {{ console.print_line(u{k}(a).to_string()); }}")
    base += len(unary)
    for k, target in enumerate(conversions):
        shown = f"c{k}(a).to_bits().to_string()" if target.startswith("float") else f"c{k}(a).to_string()"
        lines.append(f"        if (op == {base + k}) {{ console.print_line({shown}); }}")
    lines.append("        return program.ExitCode.Ok;")
    lines.append("    };")
    lines.append(");")
    cases = []
    for op in range(len(BINARY)):
        for i in range(len(values)):
            for j in range(len(values)):
                cases.append((op, i, j))
    for op in range(len(BINARY), len(BINARY) + len(unary) + len(conversions)):
        for i in range(len(values)):
            cases.append((op, i, 0))
    return "\n".join(lines) + "\n", cases


def dense_float_values(width):
    """Boundary bit patterns of a binary format: signed zeros, the smallest
    and largest subnormals, the smallest normal, 1 and its neighbours, the
    largest finite value, infinities, quiet and signalling NaNs with
    payloads, powers whose exponents differ from 1's by 0, 1, 2, p - 1, p,
    and p + 1 (p the significand's width) with mantissas that make rounding
    ties and near-cancellation, and products near overflow and underflow."""
    fraction = 23 if width == 32 else 52
    exponent_bits = width - 1 - fraction
    bias = (1 << (exponent_bits - 1)) - 1
    sign = 1 << (width - 1)
    infinity = ((1 << exponent_bits) - 1) << fraction
    ones = (1 << fraction) - 1
    half = 1 << (fraction - 1)

    def value(power, mantissa=0):
        return ((bias + power) << fraction) | (mantissa & ones)

    magnitudes = {0, 1, ones, 1 << fraction, value(0), value(0, 1), value(0, ones), value(0, half), value(-1, ones),
                  value(1), value(bias, ones), value(bias, ones - 1), infinity,
                  infinity | half, infinity | half | 0x123, infinity | 1, infinity | 0x2a,
                  value(bias // 2), value(bias // 2 + 1), value(-(bias // 2) - fraction // 2), value(1 - bias, ones),
                  value(fraction), value(fraction + 1, 1), value(0, 0x5555555555555555)}
    for d in (1, 2, fraction, fraction + 1, fraction + 2):
        for mantissa in (0, 1, half | 1):
            magnitudes.add(value(-d, mantissa))
    values = []
    for magnitude in sorted(magnitudes):
        values += [magnitude, magnitude | sign]
    return values


FLOAT_VALUES = {"float32": dense_float_values(32), "float64": dense_float_values(64)}

FLOAT_BINARY = ["+", "-", "*", "/", "==", "!=", "<", "<=", ">", ">="]


def float_program(name):
    width = 32 if name == "float32" else 64
    bits = f"uint{width}"
    values = FLOAT_VALUES[name]
    other = "float64" if name == "float32" else "float32"
    conversions = [other, "int8", "int32", "int64", "uint8", "uint32", "uint64"]
    lines = [
        "// Generated by scripts/tier-boundary.py: boundary arithmetic of " + name + ".",
        "let console = import:Std.Io.Console;",
        "let int64s = import:Std.Core.Int64;",
        "let program = import:Std.Program;",
        "let result = import:Std.Core.Result;",
        "",
        "let Boundary = module:program.Entry (",
    ]
    for k, op in enumerate(FLOAT_BINARY):
        result_type = "bool" if op in ("==", "!=", "<", "<=", ">", ">=") else name
        lines.append(f"    let op{k} = func(a: {name}, b: {name}) -> {result_type} {{")
        lines.append(f"        return a {op} b;")
        lines.append("    };")
    lines.append(f"    let u0 = func(a: {name}) -> {name} {{")
    lines.append("        return -a;")
    lines.append("    };")
    for k, target in enumerate(conversions):
        lines.append(f"    let c{k} = func(a: {name}) -> {target} {{")
        lines.append(f"        return a as {target};")
        lines.append("    };")
    lines.append("    let text = func(b: bool) -> string {")
    lines.append('        if (b) { return "true"; }')
    lines.append('        return "false";')
    lines.append("    };")
    lines.append("    export let.override main = func(args: string[]) -> program.ExitCode {")
    lines.append(f"        let patterns: {bits}[] = [" + ", ".join(str(v) for v in values) + "];")
    lines.append("        let op = result.value_or<int64>(int64s.parse(args[0]), 0);")
    lines.append("        let i = result.value_or<int64>(int64s.parse(args[1]), 0) as int;")
    lines.append("        let j = result.value_or<int64>(int64s.parse(args[2]), 0) as int;")
    lines.append(f"        let a = {name}.from_bits(patterns[i]);")
    lines.append(f"        let b = {name}.from_bits(patterns[j]);")
    for k, op in enumerate(FLOAT_BINARY):
        if op in ("==", "!=", "<", "<=", ">", ">="):
            lines.append(f"        if (op == {k}) {{ console.print_line(text(op{k}(a, b))); }}")
        else:
            lines.append(f"        if (op == {k}) {{ console.print_line(op{k}(a, b).to_bits().to_string()); }}")
    base = len(FLOAT_BINARY)
    lines.append(f"        if (op == {base}) {{ console.print_line(u0(a).to_bits().to_string()); }}")
    base += 1
    for k, target in enumerate(conversions):
        shown = f"c{k}(a).to_bits().to_string()" if target.startswith("float") else f"c{k}(a).to_string()"
        lines.append(f"        if (op == {base + k}) {{ console.print_line({shown}); }}")
    lines.append("        return program.ExitCode.Ok;")
    lines.append("    };")
    lines.append(");")
    cases = []
    for op in range(len(FLOAT_BINARY)):
        for i in range(len(values)):
            for j in range(len(values)):
                cases.append((op, i, j))
    for op in range(len(FLOAT_BINARY), len(FLOAT_BINARY) + 1 + len(conversions)):
        for i in range(len(values)):
            cases.append((op, i, 0))
    return "\n".join(lines) + "\n", cases


def run(command, environment=None):
    result = subprocess.run(command, capture_output=True, env=environment, stdin=subprocess.DEVNULL, timeout=3600)
    return result.returncode, result.stdout, result.stderr


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--neura", default="build/neura")
    parser.add_argument("--out", default="build/tier-boundary")
    args = parser.parse_args()
    neura = str(Path(args.neura).resolve())
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    programs = [(name, *integer_program(name, width, signed)) for name, width, signed in INTEGERS]
    programs += [(name, *float_program(name)) for name in ("float32", "float64")]
    failures = 0
    total = 0
    for name, source, cases in programs:
        path = out / f"{name}.nra"
        path.write_text(source)
        image = out / f"{name}.nvr"
        status, _, stderr = run([neura, "build", str(path), "-o", str(image)])
        if status != 0:
            sys.exit(f"{name}: build failed\n{stderr.decode(errors='replace')}")
        lists = out / f"{name}.cases"
        lists.write_text("".join(f"{op} {i} {j}\n" for op, i, j in cases))
        reference = run([neura, "run", "--tier=0", "--each", str(lists), str(image)])
        # Every block is lifted, and every region formed, when it first
        # runs: each case runs each operation once, far below the usual
        # thresholds.
        eager = dict(os.environ, NEURA_TIER_EAGER="1")
        runs = {}
        for tier in (1, 2):
            runs[f"tier {tier}"] = run([neura, "run", f"--tier={tier}", "--each", str(lists), str(image)], eager)
            runs[f"tier {tier} checked"] = run([neura, "run", f"--tier={tier}", "--each", str(lists), str(image)],
                                               dict(eager, NEURA_TIER_CHECK="1"))
        stats = run([neura, "run", "--tier=2", "--tier-stats", "--each", str(lists), str(image)], eager)
        lifted_line = next((line for line in stats[2].decode(errors="replace").splitlines()
                            if line.startswith("tier: steps")), "tier: no statistics")
        traps = reference[2].count(b": trap: ")
        same = all(other == reference for other in runs.values())
        total += len(cases)
        print(f"{name:8} {len(cases):5} cases, {traps:4} traps: {'identical' if same else 'DIFFERENT'}; "
              f"{lifted_line}", flush=True)
        if not same:
            failures += 1
            for label, other in runs.items():
                if other != reference:
                    (out / f"{name}.{label.replace(' ', '-')}.stdout").write_bytes(other[1])
                    (out / f"{name}.{label.replace(' ', '-')}.stderr").write_bytes(other[2])
            (out / f"{name}.tier-0.stdout").write_bytes(reference[1])
            (out / f"{name}.tier-0.stderr").write_bytes(reference[2])
    print(f"{len(programs)} programs, {total} cases, {failures} with differences")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
