#!/usr/bin/env python3
"""Generate the portable Unicode 17.0.0 UTS 46 mapping and NFC tables.

Pass a directory containing the three pinned Unicode data files below.
For source URLs see https://www.unicode.org/Public/17.0.0/.
"""
import argparse
from collections.abc import Iterable
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "IdnaMappingTable.txt": "87f05505dc026fdb2bff16132bdc68a8014675836882a9a2b1844540ad3be382",
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "DerivedNormalizationProps.txt": "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
}
DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"


def records(path: Path):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != FILES[path.name]:
        raise SystemExit(f"{path.name}: unexpected SHA-256")
    for line in data.decode().splitlines():
        row = line.split("#", 1)[0].strip()
        if row:
            yield [field.strip() for field in row.split(";")]


def bounds(field: str) -> tuple[int, int]:
    first, _, last = field.partition("..")
    return int(first, 16), int(last or first, 16)


def packed(values: Iterable[int]) -> str:
    return "".join(DIGITS[(value >> shift) & 63] for value in values for shift in (18, 12, 6, 0))


def output(data: Path) -> str:
    # Map and decompose rows refer to a shared array of scalar sequences.
    sequences = [0]
    interned = {(): (0, 0)}

    def intern(values):
        if values not in interned:
            interned[values] = (len(sequences), len(values))
            sequences.extend(values)
        return interned[values]

    mapping = []
    for span, status, *fields in records(data / "IdnaMappingTable.txt"):
        if status in {"ignored", "mapped"}:
            sequence = tuple(int(value, 16) for value in (fields[0] if fields else "").split())
            mapping.extend((*bounds(span), *intern(sequence)))

    exclusions = set()
    for span, name, *_ in records(data / "DerivedNormalizationProps.txt"):
        if name == "Full_Composition_Exclusion":
            start, end = bounds(span)
            exclusions.update(range(start, end + 1))

    combining, decompositions, composition = [], [], []
    for fields in records(data / "UnicodeData.txt"):
        scalar = int(fields[0], 16)
        ccc = int(fields[3])
        if ccc:
            combining.extend((scalar, ccc))
        if fields[5] and not fields[5].startswith("<"):
            sequence = tuple(int(value, 16) for value in fields[5].split())
            decompositions.extend((scalar, *intern(sequence)))
            if len(sequence) == 2 and scalar not in exclusions:
                composition.append((*sequence, scalar))

    notice = (ROOT / "stdlib/std/text/internal/unicode-case-data.nra").read_text()
    license_text = notice[notice.index("// UNICODE LICENSE V3"):notice.index("/// @brief")]
    tables = (
        ("Mapping", "First scalar, last scalar, offset and length.", mapping),
        ("Decomposition", "Scalar, canonical decomposition offset and length.", decompositions),
        ("Combining", "Scalar and nonzero canonical combining class.", combining),
        ("Composition", "Two input scalars and their canonical composition.", (value for row in sorted(composition) for value in row)),
        ("Sequences", "Interned replacement and decomposition scalars.", sequences),
    )
    lines = ["// Generated by scripts/generate-idna-tables.py from Unicode 17.0.0.",
             "// Each field uses four printable base-64 digits.", "//", license_text.rstrip(), "",
             "/// @brief Unicode 17.0.0 data for UTS 46 mapping and NFC.",
             "export let IdnaData = module ("]
    for name, description, values in tables:
        lines.extend((f"    /// @brief {description}", f'    export const {name}: string = "{packed(values)}";'))
    return "\n".join((*lines, ");", ""))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "stdlib/std/net/core/internal/idna-data.nra"
    content = output(args.data)
    if args.check:
        if content != path.read_text():
            raise SystemExit("IDNA tables are stale")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
