# Regenerates the Regex reference tests (tests/stdlib/regex/*-tests.nra other
# than regex-tests.nra, and support/regex-check.nra). Needs python3 and node
# (/usr/bin/nodejs or NODE). Run from any directory:
#     python3 -I -B tests/stdlib/regex/generators/generate.py
# gen_regex.py: the hand-picked corpus in corpus.py against python3's re.
# gen_random.py: seeded random patterns without nullable quantified items
# against python3's re. gen_js_random.py: seeded random patterns with
# nullable quantified items against ECMAScript (js_ref.js under node).
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
AREA = os.path.dirname(HERE)

def run(script):
    out = subprocess.run([sys.executable, '-I', '-B', os.path.join(HERE, script)], cwd=HERE, capture_output=True,
                         text=True, check=True).stdout
    return out.rstrip('\n').split('\n')

SUPPORT = r'''let error = import:Std.Core.Error;
let optional = import:Std.Core.Optional;
let regex = import:Std.Text.Regex;
let result = import:Std.Core.Result;
let test = import:Std.Test;

// Shared checks for the regex tests. `check` compares find_all with an
// expected list holding, per match, the start and end byte offsets of group
// 0 and of every group (-1, -1 when it did not participate), and checks
// is_match, matches_fully, find, and split against the same matches.
export let RegexCheck = module (
    // Flags: 1 ignore_ascii_case, 2 multi_line, 4 dot_all.
    export let compile_flags = func(pattern: string, flags: int) -> regex.Regex {
        let options = new regex.RegexFlags();
        options.ignore_ascii_case = (flags & 1) != 0;
        options.multi_line = (flags & 2) != 0;
        options.dot_all = (flags & 4) != 0;
        match (regex.compile_with(pattern, options)) {
            result.Result.Ok(compiled) => {
                return compiled;
            },
            result.Result.Err(e) => {
                trap_with_message(pattern + ": " + error.message(e));
            },
        }
    };

    export let spans = func(r: regex.Regex, m: regex.RegexMatch) -> int[list] {
        let values: int[list] = [];
        let g = 0;
        while (g <= r.group_count()) {
            let start = m.group_start(g);
            match (m.group(g)) {
                optional.Optional.Some(text) => {
                    values.append(start);
                    values.append(start + text.byte_length);
                },
                optional.Optional.None => {
                    test.assert_equal_int32(-1, start);
                    values.append(-1);
                    values.append(-1);
                },
            }
            g = g + 1;
        }
        return values;
    };

    export let check = func(pattern: string, flags: int, input: string, full: bool, expected: int[list]) -> void {
        let r = compile_flags(pattern, flags);
        let actual: int[list] = [];
        let all = r.find_all(input);
        for (let m in all) {
            for (let value in spans(r, m)) {
                actual.append(value);
            }
            test.assert_equal_string(input.slice(m.start(), m.end()), m.text());
        }
        if (!expected.equals(actual)) {
            test.fail(pattern + " on <" + input + ">: expected " + expected.to_string() + ", got " + actual.to_string());
        }
        test.assert_equal_bool(expected.length > 0, r.is_match(input));
        test.assert_equal_bool(full, r.matches_fully(input));
        let first = r.find(input);
        if (all.length == 0) {
            test.assert(first == nil);
        } else {
            test.assert(spans(r, first).equals(spans(r, all[0])));
        }
        let pieces = r.split(input);
        test.assert_equal_int32(all.length + 1, pieces.length);
    };
);
'''
open(os.path.join(AREA, 'support', 'regex-check.nra'), 'w').write(SUPPORT)

def emit(lines, out_file, module, header, per):
    chunks = [lines[i:i+per] for i in range(0, len(lines), per)]
    body = []
    for n, chunk in enumerate(chunks):
        body.append('    export let test_cases_%d = func() -> void {' % (n + 1))
        body += [l.replace('        check(', '        regex_check.check(') for l in chunk]
        body.append('    };')
        body.append('')
    src = 'let regex_check = import:RegexCheck;\n\n' + header + 'let %s = module (\n' % module + '\n'.join(body).rstrip('\n') + '\n);\n'
    open(out_file, 'w').write(src)

COMMON = '''// Python ran each pattern with re.ASCII and the IGNORECASE, MULTILINE, and
// DOTALL flags matching the test's flags (1, 2, 4), with $ without
// multi_line translated to \\Z, (?<name> to (?P<name>, and \\u{X} to
// \\UXXXXXXXX. find_all was emulated with pattern.search(input, pos),
// resuming one scalar after an empty match, as Stdlib.md 8.4 specifies;
// `full` is re.fullmatch. Generated by generators/generate.py; do not edit by hand.
'''
emit(run('gen_regex.py'), os.path.join(AREA, 'reference-tests.nra'), 'RegexReferenceTests',
     '// Matches of one hand-picked pattern per construct compared with\n// python3\'s re module.\n' + COMMON, 50)
emit(run('gen_random.py'), os.path.join(AREA, 'random-tests.nra'), 'RegexRandomTests',
     '// Seeded random patterns and inputs compared with python3\'s re module. The\n// generator never quantifies an item that can match empty and never runs\n// \\B on an empty input, the two places where Python\'s results differ\n// (see regex-tests.nra).\n' + COMMON, 100)
emit(run('gen_js_random.py'), os.path.join(AREA, 'ecmascript-tests.nra'), 'RegexEcmaScriptTests',
     '''// Seeded random patterns in which quantified items can match the empty
// string, compared with ECMAScript (node 20, flags d, g, i, m, s). The library
// follows ECMAScript's rule that an iteration beyond a quantifier's minimum
// fails when it matches the empty string; Python accepts one such iteration,
// so these cases are not compared with Python. find_all resumes one scalar
// after an empty match; `full` wraps the pattern in (?<![\\s\\S])(?:...)(?![\\s\\S]).
// Offsets are UTF-8 byte offsets. Generated by generators/generate.py; do not edit by hand.
''', 100)
